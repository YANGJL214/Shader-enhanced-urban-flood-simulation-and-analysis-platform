const getStoredLocale = () => {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    return Object.hasOwn(messages, stored) ? stored : DEFAULT_LOCALE
  } catch (_) {
    return DEFAULT_LOCALE
  }
}

export const locale = ref(getStoredLocale())

const resolveMessage = (targetLocale, key) => key.split('.').reduce((value, part) => value?.[part], messages[targetLocale])

export const t = (key, params = {}) => {
  const value = resolveMessage(locale.value, key) ?? resolveMessage(DEFAULT_LOCALE, key) ?? key
  if (typeof value !== 'string') return key
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

export const setLocale = (nextLocale) => {
  if (!Object.hasOwn(messages, nextLocale)) return
  locale.value = nextLocale
  try {
    localStorage.setItem(STORAGE_KEY, nextLocale)
  } catch (_) {
    // Storage may be disabled in sandboxed embeddings; the in-memory language still works.
  }
}

export const toggleLocale = () => setLocale(locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')

export const useI18n = () => ({ locale, setLocale, toggleLocale, t })
